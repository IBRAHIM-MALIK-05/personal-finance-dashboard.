"""Write the MySQL DDL for every table to db/schema.sql (open it in MySQL Workbench).

    python scripts/export_schema.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sqlalchemy.dialects import mysql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from finance.db import metadata  # noqa: E402

dialect = mysql.dialect()
parts = ["-- Generated by scripts/export_schema.py from finance/db.py. Do not edit by hand.",
         "-- Personal Finance & Budget Dashboard: MySQL 8 schema (InnoDB, utf8mb4).",
         "-- Money is BIGINT paisa (1 rupee = 100 paisa); financial dates are DATE.", "",
         "USE hci_finance;", ""]
for table in metadata.sorted_tables:
    ddl = str(CreateTable(table).compile(dialect=dialect)).strip()
    parts.append(ddl + " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;\n")
    for idx in table.indexes:
        parts.append(str(CreateIndex(idx).compile(dialect=dialect)).strip() + ";\n")
out = ROOT / "db" / "schema.sql"
out.write_text("\n".join(parts), encoding="utf-8")
print(f"Wrote {out}")
